#pragma once 
#include <string>
#include <atomic>

namespace SwarmIDE::Core {

    /**
     * @struct ModelAsset
     * @brief Структура метаданных и состояния языковой модели (LLM).
     * @details Описывает конкретную нейросетевую модель (например, Llama, Mistral), 
     * её расположение на диске, параметры для скачивания, а также текущий статус загрузки.
     * 
     * @note Поля состояния (`isDownloaded`, `isDownloading`, `progress`) являются потокобезопасными 
     * (`std::atomic`). Это позволяет фоновому потоку скачивания (через CPR/Curl) обновлять прогресс, 
     * а основному графическому потоку ImGui — плавно отрисовывать ProgressBar без блокировки UI.
     * 
     * @see SwarmIDE::Core::ModelManager
     * @see SwarmIDE::Nodes::BaseAgent
     */
    struct ModelAsset {
        std::string id;                          /**< Уникальный строковый идентификатор модели в системе SwarmIDE (например, "llama-3-8b-q4"). */
        std::string name;                        /**< Отображаемое человекочитаемое имя модели в интерфейсе (например, "Llama 3 8B (Q4_K_M)"). */
        std::string filepath;                    /**< Абсолютный или относительный путь к файлу модели `.gguf` на локальном диске. */
        std::string fileIcon;                    /**< Путь к файлу текстуры/иконки провайдера модели для отображения на холсте или в меню. */
        std::string downloadUrl;                 /**< Прямая ссылка (URL) для загрузки файла модели с удаленного сервера (например, Hugging Face). */

        // =====================================================================
        // Асинхронные потокобезопасные флаги состояния (UI / Network Sync)
        // =====================================================================
        
        std::atomic<bool> isDownloaded{false};   /**< Флаг: завершена ли загрузка модели. `true` — файл готов для инференса через llama.cpp. */
        std::atomic<bool> isDownloading{false};  /**< Флаг: выполняется ли скачивание файла сетевым клиентом прямо сейчас. */
        std::atomic<float> progress{0.0f};       /**< Текущий прогресс скачивания модели. Изменяется строго в диапазоне от `0.0f` (старт) до `1.0f` (завершено). */
    };

}
